#include<iostream>
using namespace std;
int main()
{
int a = 90;
int b = 100;
cout<<"we will see about operators in C++"<<endl;
cout<<"ARITHMETIC OPERATORS"<<endl;
cout<<"a + b = "<<a+b<<endl;
cout<<"a - b = "<<a-b<<endl;
cout<<"a * b = "<<a*b<<endl;
cout<<"a / b = "<<a/b<<endl;
cout<<"a % b = "<<a%b<<endl;
cout<<"a++ = "<<a++<<endl;
cout<<"++a = "<<++a<<endl;
cout<<endl;

//COMPARISON OPERATORS
//ZERO MEANS FALSE AND ONE MEANS TRUE
cout<<"COMPARISON OPERATORS"<<endl;
cout<<"a == b = "<<(a==b)<<endl;
cout<<"a != b = "<<(a!=b)<<endl;
cout<<"a > b = "<<(a>b)<<endl;
cout<<"a < b = "<<(a<b)<<endl;
cout<<"a >= b = "<<(a>=b)<<endl;
cout<<"a <= b = "<<(a<=b)<<endl;


//LOGICAL OPERATORS
cout<<"LOGICAL OPERATORS"<<endl;
cout<<"(a==b) && (a<b) = "<<((a==b) && (a<b))<<endl;
cout<<"(a==b) || (a<b) = "<<((a==b) || (a<b))<<endl;    
cout<<"!(a==b) = "<<(!(a==b))<<endl;
cout<<endl;
 


return 0;








}